def test_primary_counts_match_the_platform_table():
    """Counting primaries by page reproduces docs/diaries.md's platforms table.

    ТОР and the federal portal share `myschool-federal.md`; the table's row
    counts ТОР, and the portal is never anybody's primary.
    """
    platforms = _committed()["platforms"]
    now: Counter[str] = Counter()
    moving: Counter[str] = Counter()
    for _, system in _systems():
        page = platforms[system["platform"]]["page"]
        if page is None:
            continue
        if system["role"] == "primary":
            now[page] += 1
        elif system["role"] == "migrating_to":
            moving[page] += 1

    table = generator.platform_table(generator.DIARIES_MD.read_text(encoding="utf-8"))
    assert {page: counts for page, counts in table.items() if any(counts)} == {
        page: (now[page], moving[page]) for page in set(now) | set(moving)
    }
    # The two primaries the table cannot count, because neither has a page.
    unpaged = [
        system["platform"] for _, system in _systems()
        if system["role"] == "primary" and platforms[system["platform"]]["page"] is None
    ]
    assert sorted(unpaged) == ["it-school-penza", "paper"]


def test_only_petersburg_and_password_netschool_are_signable():
    """The one place the catalog could open a door the decision record keeps shut.

    Sign-in here means the app's own form, sending a password straight to the
    provider: Petersburg, and the sixteen «Сетевой город» regions whose
    allow-list row takes a password. ТОР and the three Госуслуги-only regions
    are hand-offs to a page in the browser, and nothing about signing in to
    Госуслуги inside the app may enter the catalog in any form.
    """
    signable = {
        (region["key"], system["platform"])
        for region, system in _systems()
        if system["action"] == "signin"
    }
    password_regions = {row.key for row in allow_list.listed()}
    assert len(password_regions) == 16
    assert signable == {("saint-petersburg", "petersburg")} | {
        (key, "netschool") for key in password_regions
    }

    for region, system in _systems():
        assert system["action"] in ("signin", "handoff", "none")
        if system["role"] in ("legacy", "unclear"):
            assert system["action"] == "none", (region["key"], system["platform"])
        if system["action"] == "handoff":
            if system["platform"] == "tor-myschool":
                assert system["handoff_url"] == "https://www.gosuslugi.ru/school"
            else:
                row = allow_list.get(region["key"])
                assert system["platform"] == "netschool" and row is not None
                assert not row.password
                assert system["handoff_url"] == row.origin
        else:
            assert system["handoff_url"] is None
        if system["action"] == "signin" and system["platform"] == "petersburg":
            assert system["web_url"] == PETERSBURG_ORIGIN

    handed_to_origin = {
        region["key"] for region, system in _systems()
        if system["action"] == "handoff" and system["platform"] == "netschool"
    }
    assert handed_to_origin == {"altai-krai", "primorye", "tula"}

    for text in (_committed_text(), generator.OVERLAY.read_text(encoding="utf-8")):
        lowered = text.casefold()
        for forbidden in ("signin_surface", "webview", "на странице дневника"):
            assert forbidden not in lowered, forbidden


