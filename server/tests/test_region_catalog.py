def test_the_committed_catalog_is_what_the_generator_writes():
    """A survey edit that is not followed by `python -m scripts.region_catalog` fails here.

    The phone bundles the committed file, so a regions.md fix that never reached
    the JSON is a fix no family sees — and the same holds for regions.py: an
    origin moved in the allow-list and not in the catalog leaves the phone
    signing in somewhere the server refuses to follow.
    """
    assert _committed_text() == _built_text(), (
        "app/catalog/data/regions.json is stale: run `python -m scripts.region_catalog` "
        "from server/ and commit the result"
    )


def test_the_check_flag_fails_on_a_catalog_that_drifted(tmp_path, monkeypatch, capsys):
    stale = tmp_path / "regions.json"
    stale.write_text(_built_text().replace('"leningrad"', '"lenobl"', 1), encoding="utf-8")
    monkeypatch.setattr(generator, "OUTPUT", stale)
    monkeypatch.setattr(generator, "ROOT", tmp_path)

    assert generator.main(["--check"]) == 1
    assert "is not what the survey implies" in capsys.readouterr().err

    stale.write_text(_built_text(), encoding="utf-8")
    assert generator.main(["--check"]) == 0


def test_eighty_nine_regions_in_the_survey_order():
    regions = _committed()["regions"]

    assert len(regions) == 89
    assert [region["name_ru"] for region in regions] == _headings()
    assert [region["order"] for region in regions] == list(range(1, 90))
    # Art. 65 order, which is not alphabetical: Russian collation would file
    # every «Республика …» under Р, and the survey's first region is a republic.
    assert regions[0]["key"] == "adygea" and regions[-1]["key"] == "yanao"
    assert sum(region["mandatory"] for region in regions) == 13


def test_keys_are_unique_slugs_and_codes_unique_two_digits():
    regions = _committed()["regions"]
    keys = [region["key"] for region in regions]
    codes = [region["code"] for region in regions]

    assert len(set(keys)) == 89
    assert len(set(codes)) == 89
    for region in regions:
        # The width of classes.diary_region and diary_sessions.region, and the
        # pattern the registration body checks a region against.
        assert re.fullmatch(r"[a-z0-9-]{2,32}", region["key"]), region["key"]
        assert re.fullmatch(r"\d\d", region["code"]), region["code"]
    assert {key: code for key, code in zip(keys, codes, strict=True)}["crimea"] == "91"
    assert {key: code for key, code in zip(keys, codes, strict=True)}["sevastopol"] == "92"


def test_the_nineteen_netschool_keys_are_the_allow_lists_own():
    """The keys the database stores, byte for byte — and everything else the phone trusts.

    `classes.diary_region`, `diary_sessions.region` and the sealed credential all
    hold these strings. A catalog key that differed by a letter would leave every
    class bound to that region looking unbound on the phone, and an origin that
    differed would be a second allow-list.
    """
    regions = _regions()
    rows = allow_list.listed(password_only=False)
    assert len(rows) == 19

    for row in rows:
        region = regions[row.key]
        assert region["name_ru"] == row.title
        (linked,) = [system for system in region["systems"] if system["netschool"]]
        assert linked["netschool"] == {
            "region": row.key,
            "origin": row.origin,
            "password": row.password,
            "verified": row.verified,
            "zone": row.zone,
        }


