"""The region catalog: generated from the survey, committed, and read by both halves.

`app/catalog/data/regions.json` is what the phone's onboarding lists, searches and
recommends from, and what the server's school directory places a school with. It
is generated by `scripts/region_catalog.py` from `docs/diaries/regions.md`, the
netschool allow-list and a hand overlay, and every decision in it — which system
can be signed into, which is handed off to Госуслуги, which is put first — is
made there and read everywhere else.

Three kinds of test live here. The drift test, which makes a survey edit without
the regenerated catalog a red build. The contract tests, which hold the catalog to
the things other code stores or trusts: region keys that sit in database columns,
origins a sign-in may go to, zones, DaData's spellings. And the parser tests,
which pin the traps the survey's markdown sets — a full stop inside «Since», a
label that is itself «Е-услуги. Образование», a port, an IDN and its punycode twin,
one page that means two platforms.
"""

from __future__ import annotations

import fnmatch
