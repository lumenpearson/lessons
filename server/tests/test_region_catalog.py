ROOT = Path(__file__).resolve().parents[2]
SERVER = ROOT / "server"


@functools.cache
def _overlay() -> dict[str, Any]:
    return tomllib.loads(generator.OVERLAY.read_text(encoding="utf-8"))


@functools.cache
def _built_text() -> str:
    return generator.render(generator.build_from_repository())


@functools.cache
def _committed_text() -> str:
    return catalog.DATA.read_text(encoding="utf-8")


def _committed() -> dict[str, Any]:
    # A fresh parse each time: a test that edits what it is handed must not edit
    # what the next test reads.
    return json.loads(_committed_text())


def _regions() -> dict[str, dict[str, Any]]:
    return {region["key"]: region for region in _committed()["regions"]}


def _systems() -> list[tuple[dict[str, Any], dict[str, Any]]]:
    return [(region, system) for region in _committed()["regions"] for system in region["systems"]]


def _headings() -> list[str]:
    text = generator.REGIONS_MD.read_text(encoding="utf-8")
    return re.findall(r"^## (.+?)\s*$", text, flags=re.MULTILINE)


