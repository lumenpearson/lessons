def test_the_loader_places_a_school_by_code_or_by_dadatas_spelling():
    assert catalog.get("leningrad").name_en == "Leningrad Oblast"
    assert catalog.get("nowhere") is None and catalog.get(None) is None
    assert catalog.by_code("47").key == "leningrad"
    assert catalog.by_code("78").key == "saint-petersburg"
    # A thirteen-digit KLADR id is the caller's to cut, and a guess is worse than a miss.
    assert catalog.by_code("4700000000000") is None
    assert catalog.by_code("4") is None and catalog.by_code(None) is None
    assert catalog.by_dadata_name("Респ Татарстан").key == "tatarstan"
    assert catalog.by_dadata_name("г. Москва").key == "moscow"
    assert catalog.by_dadata_name("Кемеровская область — Кузбасс").key == "kemerovo"
    assert catalog.by_dadata_name("РЕСП САХА (ЯКУТИЯ)").key == "yakutia"
    # «Алтай» is the republic and «Алтайский» the krai: exact, never partial.
    assert catalog.by_dadata_name("Алтай").key == "altai-republic"
    assert catalog.by_dadata_name("Алтайский край").key == "altai-krai"
    assert catalog.by_dadata_name("Алт") is None
    assert len(catalog.regions()) == 89


