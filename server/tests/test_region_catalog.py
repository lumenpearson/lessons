def test_a_full_stop_inside_since_or_a_label_does_not_move_the_hosts():
    """Anchored on «Hosts:», «Since:» and «Confidence:», never on the first full stop."""
    (region,) = generator.parse_survey(_BLOCK)

    assert region.name == "Республика Бурятия"
    assert region.mandatory
    primary, admissions = region.systems[0], region.systems[1]
    assert [host.display() for host in primary.hosts] == ["deti.obr03.ru", "sad06.ru:82"]
    assert primary.confidence == "high" and primary.page == "netschool"
    assert admissions.label == "Е-услуги. Образование" and admissions.page is None
    assert [host.display() for host in admissions.hosts] == ["es.zabedu.ru"]
    # Only the first line of a bullet is read: evidence and «Notes.» are prose.
    everything = [host.display() for system in region.systems for host in system.hosts]
    assert "evidence.example" not in everything and "not.a.system" not in everything


