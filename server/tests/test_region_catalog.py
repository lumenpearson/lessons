def test_the_summary_table_is_held_to_the_survey():
    regions_md = generator.REGIONS_MD.read_text(encoding="utf-8")
    table_md = generator.DIARIES_MD.read_text(encoding="utf-8")
    survey = generator.parse_survey(regions_md)
    generator.cross_check(survey, table_md)

    # Ленинградская's primary is «Сетевой город»; a table that said otherwise
    # would be one of the two documents lying about a region's diary.
