def _ignored_by(pattern: str, relative: str) -> bool:
    """One `.vercelignore` line against one path, by gitignore's rules as Vercel reads them."""
    directory_only = pattern.endswith("/")
    core = pattern.strip("/")
    parts = relative.split("/")
    if "/" in core:
        # Anchored at the root: it names a directory by its path (or a file, if
        # it has no trailing slash).
        prefixes = ["/".join(parts[: i + 1]) for i in range(len(parts) - 1)]
        if not directory_only:
            prefixes.append(relative)
        return any(fnmatch.fnmatch(prefix, core) for prefix in prefixes)
    # Unanchored: it names a component at any depth, a directory's only if it ends in «/».
    candidates = parts[:-1] if directory_only else parts
    return any(fnmatch.fnmatch(part, core) for part in candidates)


def test_the_catalog_sits_where_vercel_ships_it():
    """Under `server/app/`, matched by nothing in `.vercelignore`, and packaged.

    `server/scripts/` is ignored on purpose — the generator never runs in a
    request — so the catalog must not live beside it, and the loader must not
    read the overlay. Whether Vercel then uploads a `.json` next to the code is
    inferred rather than seen: the first preview deploy's directory call is what
    settles it.
    """
    data = catalog.DATA.relative_to(ROOT).as_posix()
    loader = Path(catalog.__file__).resolve().relative_to(ROOT).as_posix()
    assert data.startswith("server/app/")

    patterns = [
        line.strip()
        for line in (ROOT / ".vercelignore").read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    ]
    assert _ignored_by("server/scripts/", "server/scripts/region_catalog.toml")
    for path in (data, loader):
        assert not [pattern for pattern in patterns if _ignored_by(pattern, path)], path

    pyproject = tomllib.loads((SERVER / "pyproject.toml").read_text(encoding="utf-8"))
    assert "catalog/data/*.json" in pyproject["tool"]["setuptools"]["package-data"]["app"]


