# ---------------------------------------------------------------- Android VectorDrawables
def vd_color(hex_, a=1.0):
    return "#" + f"{round(a * 255):02X}" + hex_[1:].upper()


def vd_fill(g, ind):
    if g["kind"] == "linear":
        attrs = (f'android:type="linear" android:startX="{c.fmt(g["x1"])}" android:startY="{c.fmt(g["y1"])}" '
                 f'android:endX="{c.fmt(g["x2"])}" android:endY="{c.fmt(g["y2"])}"')
    else:
        attrs = (f'android:type="radial" android:centerX="{c.fmt(g["cx"])}" android:centerY="{c.fmt(g["cy"])}" '
                 f'android:gradientRadius="{c.fmt(g["r"])}"')
    items = "".join(f'\n{ind}        <item android:offset="{o}" android:color="{vd_color(col, a)}"/>'
                    for o, col, a in g["stops"])
    return (f'\n{ind}<aapt:attr name="android:fillColor">\n{ind}    <gradient {attrs}>{items}'
            f'\n{ind}    </gradient>\n{ind}</aapt:attr>')


def vd_path(d, ind, fill=None, grad=None, alpha=None, evenodd=False):
    a = f'\n{ind}    android:fillAlpha="{alpha}"' if alpha is not None else ""
    e = f'\n{ind}    android:fillType="evenOdd"' if evenodd else ""
    if grad:
        return f'{ind}<path\n{ind}    android:pathData="{d}"{a}{e}>{vd_fill(grad, ind + "    ")}\n{ind}</path>'
    return f'{ind}<path\n{ind}    android:pathData="{d}"\n{ind}    android:fillColor="{fill}"{a}{e}/>'


def vd_foreground(key=None):
    """108 dp adaptive layer; the dial's tips sit at FILL × 36 dp (inside the 33 dp safe radius ×1.0)."""
    k = c.FILL * 36 / c.R
    t = 54 - 128 * k
    mono = key is None
    if not mono:
        base, glow, echoes = c.gradients(key)
    note = ("Monochrome layer (Android 13+ themed icons): alpha carries the trail." if mono else
            f"«Дневник», palette «{c.PALETTES[key][0]}». Generated by build_pack.py — edit clock.py, not this file.")
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {note}",
        "     A 12-lobe dial reading five o'clock; five turned, fading copies behind it (the trail)",
        "     are clipped by everything-but-the-cut-outs, so the hands and marks stay clean. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    xmlns:aapt="http://schemas.android.com/aapt"',
        '    android:width="108dp"', '    android:height="108dp"',
        '    android:viewportWidth="108"', '    android:viewportHeight="108">',
        f'    <group\n        android:scaleX="{k:.5f}"\n        android:scaleY="{k:.5f}"\n'
        f'        android:translateX="{t:.4f}"\n        android:translateY="{t:.4f}">',
        "        <group>",
        f'            <clip-path android:pathData="{c.holes_clip_d()}"/>',
    ]
    for i, (rot, sc, alpha) in enumerate(c.ECHOES):
        if mono:
            out.append(vd_path(c.dial(rot, sc), " " * 12, fill="#FFFFFFFF", alpha=alpha))
        else:
            out.append(vd_path(c.dial(rot, sc), " " * 12, grad=echoes[i], alpha=alpha))
    out.append("        </group>")
    body = c.body_d()
    if mono:
        out.append(vd_path(body, " " * 8, fill="#FFFFFFFF", evenodd=True))
    else:
        out.append(vd_path(body, " " * 8, grad=base, evenodd=True))
        out.append(vd_path(body, " " * 8, grad=glow, evenodd=True))
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


def build_android():
    res = PACK / "android" / "res"
    write(res / "values" / "ic_launcher_background_white.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          '    <color name="ic_launcher_background_white">#FFFFFF</color>\n</resources>\n')
    write(res / "drawable" / "ic_launcher_monochrome.xml", vd_foreground(None))
    for k in KEYS:
        rn = res_name(k)
        write(res / "drawable" / f"ic_launcher_foreground_{rn}.xml", vd_foreground(k))
        adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                    '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                    '    <background android:drawable="@color/ic_launcher_background_white"/>\n'
                    f'    <foreground android:drawable="@drawable/ic_launcher_foreground_{rn}"/>\n'
                    '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
                    '</adaptive-icon>\n')
        write(res / "mipmap-anydpi-v26" / f"ic_launcher_{rn}.xml", adaptive)
        write(res / "mipmap-anydpi-v26" / f"ic_launcher_{rn}_round.xml", adaptive)


# ---------------------------------------------------------------- previews
def cell(x, y, size, inner, mask="circle", uid="", shadow=True):
    if mask == "circle":
        shape = '<circle cx="128" cy="128" r="128"/>'
    elif mask == "squircle":
        from icon import squircle
        shape = f'<path d="{squircle(0, 0, 256)}"/>'
    else:
        shape = '<rect width="256" height="256"/>'
    sh = (f'<filter id="sh{uid}" x="-20%" y="-20%" width="140%" height="150%"><feDropShadow dx="0" dy="4" '
          f'stdDeviation="6" flood-color="#1B2050" flood-opacity=".2"/></filter>') if shadow else ""
    pad = size * 12 / 256   # the shadow margin sits outside, so the icon itself is exactly `size` px
    return (f'<svg x="{x - pad:.2f}" y="{y - pad:.2f}" width="{size + 2 * pad:.2f}" height="{size + 2 * pad:.2f}" '
            f'viewBox="-12 -12 280 280" overflow="visible">'
            f'<defs><clipPath id="cp{uid}">{shape}</clipPath>{sh}</defs>'
            f'<g{f" filter=\"url(#sh{uid})\"" if shadow else ""}><g clip-path="url(#cp{uid})">{inner}</g></g></svg>')


def text(x, y, t, size=20, fill="#3A3F5C", weight=400, anchor="middle"):
    return (f'<text x="{x}" y="{y}" text-anchor="{anchor}" font-family="Segoe UI, Roboto, sans-serif" '
            f'font-size="{size}" font-weight="{weight}" fill="{fill}">{t}</text>')


