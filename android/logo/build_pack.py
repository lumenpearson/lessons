# ---------------------------------------------------------------- PNG (Chrome via render_png.py)
def render(files, size, out_dir, bg=None):
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = [sys.executable, str(RENDER), *map(str, files), "--out-dir", str(out_dir), "--size", str(size)]
    if bg:
        cmd += ["--bg", bg]
    subprocess.run(cmd, check=True, capture_output=True)


def render_one(src, out, w, h):
    subprocess.run([sys.executable, str(RENDER), str(src), "-o", str(out), "--width", str(w), "--height", str(h)],
                   check=True, capture_output=True)


def build_png():
    tmp = PACK / "_tmp"
    syms = [PACK / "svg" / k / f"dnevnik-{k}-symbol.svg" for k in KEYS]
    icons = [PACK / "svg" / k / f"dnevnik-{k}-icon.svg" for k in KEYS]
    smalls = [PACK / "svg" / k / f"dnevnik-{k}-small.svg" for k in KEYS]
    masks = [PACK / "svg" / k / f"dnevnik-{k}-maskable.svg" for k in KEYS]
    monos = sorted((PACK / "svg" / "mono").glob("*.svg"))
    jobs = [(syms + monos, 1024, "sym1024"), (syms + monos, 512, "sym512"), (syms, 256, "sym256"),
            (icons, 512, "icon512"), (icons, 192, "icon192"), (icons, 180, "icon180"),
            (masks, 512, "mask512"), (smalls, 48, "s48"), (smalls, 32, "s32"), (smalls, 16, "s16")]
    for files, size, tag in jobs:
        render(files, size, tmp / tag)
    for k in KEYS:
        pd, wd = PACK / "png" / k, PACK / "web" / k
        pd.mkdir(parents=True, exist_ok=True)
        for s in (1024, 512, 256):
            shutil.copyfile(tmp / f"sym{s}" / f"dnevnik-{k}-symbol.png", pd / f"dnevnik-{k}-symbol-{s}.png")
        shutil.copyfile(tmp / "icon512" / f"dnevnik-{k}-icon.png", pd / f"dnevnik-{k}-play-store-512.png")
        shutil.copyfile(tmp / "icon512" / f"dnevnik-{k}-icon.png", wd / "icon-512.png")
        shutil.copyfile(tmp / "icon192" / f"dnevnik-{k}-icon.png", wd / "icon-192.png")
        shutil.copyfile(tmp / "icon180" / f"dnevnik-{k}-icon.png", wd / "apple-touch-icon.png")
        shutil.copyfile(tmp / "mask512" / f"dnevnik-{k}-maskable.png", wd / "maskable-512.png")
        for s in (16, 32, 48):
            shutil.copyfile(tmp / f"s{s}" / f"dnevnik-{k}-small.png", wd / f"favicon-{s}.png")
        subprocess.run([sys.executable, str(RENDER), str(PACK / "svg" / k / f"dnevnik-{k}-small.svg"),
                        "--ico", str(wd / "favicon.ico"), "--ico-sizes", "16", "32", "48"],
                       check=True, capture_output=True)
    md = PACK / "png" / "mono"
    md.mkdir(parents=True, exist_ok=True)
    for f in monos:
        for s in (1024, 512):
            shutil.copyfile(tmp / f"sym{s}" / f"{f.stem}.png", md / f"{f.stem}-{s}.png")
    render_one(PACK / "previews" / "overview.svg", PACK / "previews" / "overview.png", 1600, 1330)
    render_one(PACK / "previews" / "detail.svg", PACK / "previews" / "detail.png", 1400, 720)
    shutil.rmtree(tmp)


def write_readme():
    rows = ["| Вариант | Папка / ресурс | Центр и верх · кольцо 53 % · край |", "| --- | --- | --- |"]
    for k in KEYS:
        name, stops = c.PALETTES[k]
        star = " ★" if k == RECOMMENDED else ""
        rows.append(f"| {name}{star} | `{k}` / `{res_name(k)}` | " + " · ".join(f"`{h}`" for h in stops) + " |")
    text = (HERE / "pack-readme.md").read_text(encoding="utf-8").replace("{{TABLE}}", "\n".join(rows))
    write(PACK / "README.md", text)


if __name__ == "__main__":
    if PACK.exists():
        shutil.rmtree(PACK)
    build_svg()
    build_android()
    build_previews()
    build_web_texts()
    write_readme()
    if "--no-png" not in sys.argv:
        build_png()
    print("pack:", PACK)
