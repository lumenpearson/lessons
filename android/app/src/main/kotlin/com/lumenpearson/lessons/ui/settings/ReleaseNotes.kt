/**
 * A GitHub release body, rendered.
 *
 * Not a Markdown library. The bodies this renders are written by one person or
 * generated by GitHub, and between them they use six constructs: headings,
 * bullets, bold, code, links and blank lines. A real parser would be the
 * largest dependency in the app in service of its smallest screen, and it would
 * lay out tables and images that a sheet has no room for anyway. Everything
 * this does not recognise is shown as the line it was, which is what GitHub
 * does with text it does not understand either.
 *
 * A pure function of the string: the same body always produces the same tree,
 * and [parseReleaseNotes] can be checked without a composition.
 */
@Composable
fun ReleaseNotes(markdown: String, modifier: Modifier = Modifier) {
    val blocks = remember(markdown) { parseReleaseNotes(markdown) }
    val scheme = MaterialTheme.colorScheme
    // Keyed on the two colours it reads rather than on the scheme: ColorScheme
    // has no value equality, so the scheme itself would rebuild the styles on
    // every recomposition.
    val styles = remember(scheme.primary, scheme.surfaceContainer) {
        InlineStyles(
            bold = SpanStyle(fontWeight = FontWeight.Bold),
            // The page colour, not a "highest" surface. The notes sit on a
            // surfaceBright card, and the tonal step just above that is
            // invisible in a dark scheme. A hole through which the page shows
            // is the same trick the 2 dp gaps between rows play, and it reads
            // in both schemes.
            code = SpanStyle(fontFamily = FontFamily.Monospace, background = scheme.surfaceContainer),
            link = TextLinkStyles(
                style = SpanStyle(
                    color = scheme.primary,
                    fontWeight = FontWeight.Medium,
                    textDecoration = TextDecoration.Underline,
                ),
            ),
        )
    }
    val changelogLabel = correctedString(R.string.update_notes_full_changelog)

    Column(modifier = modifier.fillMaxWidth()) {
        blocks.forEach { block ->
            when (block) {
                is NotesBlock.Heading -> Text(
                    text = inlineText(block.text, styles),
                    style = if (block.level <= SubheadingLevel) {
                        MaterialTheme.typography.titleMedium
                    } else {
                        MaterialTheme.typography.titleSmall
                    },
                    color = scheme.primary,
                    modifier = Modifier.padding(bottom = HeadingGap),
                )

                is NotesBlock.Bullet -> BulletRow(text = inlineText(block.text, styles))

                is NotesBlock.Paragraph -> Text(
                    text = inlineText(block.text, styles),
                    style = MaterialTheme.typography.bodyLarge,
                    modifier = Modifier.padding(vertical = LineGap),
                )

                // No onClick and no Intent, as in the about card: LinkAnnotation
                // is opened by the platform's UriHandler and is announced as a
                // link by a screen reader.
                is NotesBlock.ChangelogLink -> Text(
                    text = buildAnnotatedString {
                        withLink(LinkAnnotation.Url(url = block.url, styles = styles.link)) {
                            append(changelogLabel)
                        }
                    },
                    style = MaterialTheme.typography.bodyMedium,
                    modifier = Modifier.padding(top = LineGap),
                )

                NotesBlock.Gap -> Spacer(Modifier.height(ParagraphGap))
            }
        }
    }
}

/** "•" in a column of its own, so a wrapped line starts under the text, not under the dot. */
@Composable
private fun BulletRow(text: AnnotatedString) {
    Row(modifier = Modifier.padding(start = BulletIndent, top = LineGap, bottom = LineGap)) {
        Text(
            text = BulletGlyph,
            style = MaterialTheme.typography.bodyLarge,
            modifier = Modifier.width(BulletColumn),
        )
        Text(
            text = text,
            style = MaterialTheme.typography.bodyLarge,
            modifier = Modifier.weight(1f),
        )
    }
}

/** The three inline spans, resolved once against the theme. */
@Immutable
private class InlineStyles(
    val bold: SpanStyle,
    val code: SpanStyle,
    val link: TextLinkStyles,
)

/**
 * One line with its `**bold**`, `` `code` ``, `[text](url)` and bare URLs applied.
 *
 * Flat, not recursive: a bold span is bold text, not a sub-document. Nothing in
 * a release note nests deeper than that, and a tokenizer that does not recurse
 * cannot be made to loop by a stray asterisk.
 */
private fun inlineText(text: String, styles: InlineStyles): AnnotatedString = buildAnnotatedString {
    var cursor = 0
    for (match in InlineMarkup.findAll(text)) {
        append(text.substring(cursor, match.range.first))
        val groups = match.groupValues
        when {
            groups[CodeGroup].isNotEmpty() -> withStyle(styles.code) { append(groups[CodeGroup]) }
            groups[BoldGroup].isNotEmpty() -> withStyle(styles.bold) { append(groups[BoldGroup]) }
            groups[LinkTextGroup].isNotEmpty() -> withLink(
                LinkAnnotation.Url(url = groups[LinkUrlGroup], styles = styles.link),
            ) {
                append(groups[LinkTextGroup])
            }

            else -> withLink(LinkAnnotation.Url(url = groups[BareUrlGroup], styles = styles.link)) {
                append(groups[BareUrlGroup])
            }
        }
        cursor = match.range.last + 1
    }
    append(text.substring(cursor))
}

/** One rendered line of a release body. */
internal sealed interface NotesBlock {
    data class Heading(val level: Int, val text: String) : NotesBlock

    data class Bullet(val text: String) : NotesBlock

    data class Paragraph(val text: String) : NotesBlock

    /** GitHub's generated `**Full Changelog**: …` line, reduced to where it points. */
    data class ChangelogLink(val url: String) : NotesBlock

    data object Gap : NotesBlock
}

/**
 * Splits a body into lines and names each one.
 *
 * Line by line rather than by paragraph, because that is how GitHub renders a
 * release body: a single newline there is a line break, not a soft wrap, and a
 * list written one item per line must not collapse into one sentence.
 */
internal fun parseReleaseNotes(markdown: String): List<NotesBlock> {
    val blocks = mutableListOf<NotesBlock>()
    for (raw in HtmlComment.replace(markdown, "").lineSequence()) {
        val line = raw.trim()
        // A fence is a rendering instruction, not a line to show; what sits
        // between two of them still comes through as text.
        if (line.startsWith(Fence)) continue

        val block: NotesBlock = if (line.isEmpty()) {
            NotesBlock.Gap
        } else {
            ChangelogLine.matchEntire(line)?.let { match ->
                val target = match.groupValues[1]
                NotesBlock.ChangelogLink(url = MarkdownLinkTarget.find(target)?.groupValues?.get(1) ?: target)
            }
                ?: HeadingLine.matchEntire(line)?.let { match ->
                    NotesBlock.Heading(level = match.groupValues[1].length, text = match.groupValues[2])
                }
                ?: BulletLine.matchEntire(line)?.let { match ->
                    NotesBlock.Bullet(text = match.groupValues[1])
                }
                ?: NotesBlock.Paragraph(text = line)
        }

        // Runs of blank lines are one gap, and a body never opens with one:
        // GitHub's editor leaves a newline after every heading it generates.
        if (block == NotesBlock.Gap && (blocks.isEmpty() || blocks.last() == NotesBlock.Gap)) continue
        blocks += block
    }
    // Nor does it close with one; the card's own padding is the bottom margin.
    while (blocks.lastOrNull() == NotesBlock.Gap) blocks.removeAt(blocks.lastIndex)
    return blocks
}

/** GitHub prefixes generated notes with `<!-- Release notes generated using … -->`. */
private val HtmlComment = Regex("""<!--.*?-->""", RegexOption.DOT_MATCHES_ALL)

private val HeadingLine = Regex("""^(#{1,6})\s+(.+?)\s*#*$""")

private val BulletLine = Regex("""^[-*•]\s+(.+)$""")

private val ChangelogLine = Regex("""^\*\*Full Changelog\*\*:\s*(.+)$""")

/** The URL out of a `[label](url)`, for a changelog line written as a link. */
private val MarkdownLinkTarget = Regex("""\((https?://[^)\s]+)\)""")

private const val Fence = "```"

/**
 * Code, bold, a Markdown link, a bare URL — one alternation, so the scan is a
 * single left-to-right pass and the leftmost construct always wins. Code comes
 * first so that asterisks inside backticks stay asterisks. Bare URLs are in the
 * list because GitHub's generated bullets end in the pull request's address and
 * GitHub links it; without this a row would end in sixty characters of address
 * nobody can tap. The last character class keeps sentence punctuation out of
 * the link.
 */
private val InlineMarkup = Regex(
    """`([^`]+)`|\*\*(.+?)\*\*|\[([^\]]+)\]\(([^)\s]+)\)|(https?://[^\s<>()]*[^\s<>().,;:!?])""",
)

private const val CodeGroup = 1

private const val BoldGroup = 2

private const val LinkTextGroup = 3

private const val LinkUrlGroup = 4

private const val BareUrlGroup = 5

/** `#` and `##` are titleMedium; anything deeper is titleSmall. */
private const val SubheadingLevel = 2

private const val BulletGlyph = "•"

/** Above and below one line; consecutive lines sit 4 dp apart. */
private val LineGap = 2.dp

/** What a blank line in the body turns into. */
private val ParagraphGap = 8.dp

private val HeadingGap = 4.dp

private val BulletIndent = 8.dp

/** Width of the dot's column, so every bullet's text starts on the same x. */
private val BulletColumn = 16.dp
